/** Every ordering of 0 .. n - 1, generated by Heap's algorithm. */
function permutations(n: number): number[][] {
  const a = Array.from({ length: n }, (_, i) => i);
  const out: number[][] = [[...a]];
  const c = Array.from({ length: n }, () => 0);
  for (let i = 1; i < n;) {
    if ((c[i] as number) < i) {
      const j = i % 2 === 0 ? 0 : (c[i] as number);
      [a[j], a[i]] = [a[i] as number, a[j] as number];
      out.push([...a]);
      c[i] = (c[i] as number) + 1;
      i = 1;
    } else {
      c[i] = 0;
      i++;
    }
  }
  return out;
}

