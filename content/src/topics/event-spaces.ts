const [mO, mF] = [math`\Omega`, math`\mathcal{F}`];

/** Subsets of {1, ..., n} as bit masks: bit i - 1 set means i is in the set. */
const elems = (m: number, n: number): number[] => upTo(n).filter((i) => ((m >> (i - 1)) & 1) === 1);
const maskOf = (xs: readonly number[]): number => xs.reduce((m, i) => m | (1 << (i - 1)), 0);
const full = (n: number): number => (1 << n) - 1;
const setTex = (m: number, n: number): Span => (m === 0 ? math`\varnothing` : setOf(elems(m, n)));

/** The smallest collection containing `gens`, the empty set, and the whole set, closed under complement and union: brute force to a fixed point. */
function closure(gens: readonly number[], n: number): Set<number> {
  const out = new Set<number>([0, full(n), ...gens]);
  for (let changed = true; changed;) {
    changed = false;
    for (const a of [...out]) {
      for (const b of [a ^ full(n), ...[...out].map((x) => a | x)]) {
        if (!out.has(b)) { out.add(b); changed = true; }
      }
    }
  }
  return out;
}

/** The nonempty atoms of the events: the sets of points that no event separates. */
function atoms(events: readonly number[], n: number): number {
  const sig = new Set(upTo(n).map((i) => events.map((e) => (e >> (i - 1)) & 1).join('')));
  return sig.size;
}

