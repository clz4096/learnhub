interface PartP { n: number; blocks: number[][] }

/** A random partition of {1, ..., n} into k nonempty blocks. */
function partition(rng: () => number, n: number, k: number): number[][] {
  const shuffled = sample(rng, upTo(n), n);
  const cuts = sample(rng, upTo(n - 1), k - 1).sort((a, b) => a - b);
  const bounds = [0, ...cuts, n];
  return upTo(k).map((j) => (shuffled.slice(bounds[j - 1], bounds[j]) as number[]).sort((a, b) => a - b)).sort((a, b) => (a[0] as number) - (b[0] as number));
}

const partitionCount = generator<PartP>({
  id: 'partition-count',
  skill: 'Count the events of the sigma-algebra generated by a partition: every union of blocks.',
  params: (rng) => {
    const n = int(rng, 5, 9);
    return { n, blocks: partition(rng, n, int(rng, 2, Math.min(5, n - 1))) };
  },
  sane: ({ n, blocks }) => (blocks.flat().length === n && new Set(blocks.flat()).size === n && blocks.length >= 2 && blocks.length <= 5 ? null : 'not a partition'),
  problem: ({ n, blocks }) => {
    const k = blocks.length;
    return {
      prompt: t`Let ${math`\Omega = ${setOf(upTo(n))}`}, split into the blocks ${computedTex(blocks.map((b) => setOf(b).text).join(',\\ '))}. Let ${mF} be the collection of all unions of blocks, the empty union ${math`\varnothing`} included. It is a [[sigma-algebra|sigma-algebra]]. How many events does ${mF} contain?`,
      answer: { kind: 'exact', expected: String(2 ** k) },
      solution: [
        t`An event in ${mF} is fixed by which blocks it contains: each of the ${k} blocks is in or out.`,
        t`By the product rule that is ${math`${2}^{${k}} = ${2 ** k}`} events, from ${math`\varnothing`} (no blocks) to ${mO} (all of them).`,
        t`It is closed under complement (swap in and out) and under unions (take every block in either), so it is a sigma-algebra.`,
      ],
    };
  },
  solve: ({ n, blocks }) => String(closure(blocks.map(maskOf), n).size),
  misconceptions: ({ n, blocks }): Misconception[] => [
    { response: String(blocks.length + 2), why: t`Unions of blocks are events too, not only the blocks, ${math`\varnothing`}, and ${mO}.` },
    { response: String(2 ** n), why: t`That counts every subset of ${mO}. Here an event must be a union of whole blocks: it cannot split a block.` },
    { response: String(2 ** blocks.length - 1), why: t`The empty union, ${math`\varnothing`}, is an event as well: it is the complement of ${mO}.` },
  ],
});

interface GenP { n: number; a: number; b: number }

const generated = generator<GenP>({
  id: 'generated',
  skill: 'Count the events of the smallest sigma-algebra containing two given events, through its atoms.',
  params: (rng) => {
    for (;;) {
      const n = int(rng, 4, 7);
      const a = int(rng, 1, full(n) - 1);
      const b = int(rng, 1, full(n) - 1);
      if (a !== b && a !== (b ^ full(n))) return { n, a, b };
    }
  },
  sane: ({ n, a, b }) => (a > 0 && b > 0 && a < full(n) && b < full(n) && a !== b && a !== (b ^ full(n)) ? null : 'out of range'),
  problem: ({ n, a, b }) => {
    const k = atoms([a, b], n);
    const parts: [string, number][] = [
      ['A \\cap B', a & b], ['A \\cap B^{c}', a & ~b & full(n)], ['A^{c} \\cap B', ~a & b & full(n)], ['A^{c} \\cap B^{c}', ~a & ~b & full(n)],
    ];
    return {
      prompt: t`Let ${math`\Omega = ${setOf(upTo(n))}`}, ${math`A = ${setTex(a, n)}`}, and ${math`B = ${setTex(b, n)}`}. How many events are in the smallest sigma-algebra on ${mO} that contains ${math`A`} and ${math`B`}?`,
      answer: { kind: 'exact', expected: String(2 ** k) },
      solution: [
        t`The sigma-algebra must contain the pieces ${math`A \cap B`}, ${math`A \cap B^{c}`}, ${math`A^{c} \cap B`}, and ${math`A^{c} \cap B^{c}`}: ${computedTex(parts.map(([name, m]) => `${name} = ${setTex(m, n).text}`).join(',\\ '))}.`,
        t`The nonempty pieces, ${k} of them, form a partition, and the smallest sigma-algebra is every union of them: ${math`${2}^{${k}} = ${2 ** k}`} events.`,
      ],
    };
  },
  solve: ({ n, a, b }) => String(closure([a, b], n).size),
  misconceptions: ({ n }): Misconception[] => [
    { response: '4', why: t`${math`\varnothing`}, ${math`A`}, ${math`B`}, and ${mO} are not closed: complements and unions must be in too.` },
    { response: '6', why: t`Adding the complements is not enough: unions such as ${math`A \cup B`} and the intersections they lead to are needed too.` },
    { response: String(2 ** n), why: t`Not every subset is needed: only unions of the pieces that ${math`A`} and ${math`B`} cut ${mO} into.` },
  ],
});

interface MissP { gens: number[] }

const N4 = 4;
const missing = generator<MissP>({
  id: 'missing',
  skill: 'Find what must be added to a collection of events to close it under complements and unions.',
  params: (rng) => {
    for (;;) {
      // Two events, so that unions are needed as well as complements, and not everything is forced.
      const gens = sample(rng, upTo(full(N4) - 1), 2);
      const given = new Set([0, full(N4), ...gens]);
      const need = [...closure(gens, N4)].filter((m) => !given.has(m));
      const comps = new Set(gens.map((g) => g ^ full(N4)).filter((m) => !given.has(m)));
      if (need.length > comps.size && need.length < full(N4) - 1 - gens.length) return { gens };
    }
  },
  sane: ({ gens }) => (gens.every((g) => g > 0 && g < full(N4)) ? null : 'out of range'),
  problem: ({ gens }) => {
    const given = [...new Set([0, ...gens, full(N4)])].sort((x, y) => x - y);
    const all = [...closure(gens, N4)];
    const need = all.filter((m) => !given.includes(m)).sort((x, y) => x - y);
    const options: ChoiceOption[] = upTo(full(N4) - 1).filter((m) => !given.includes(m)).map((m) => ({ id: `s${m}`, label: [setTex(m, N4)] }));
    return {
      prompt: t`Let ${math`\Omega = ${setOf(upTo(N4))}`} and let ${mF} start as ${computedTex(given.map((m) => setTex(m, N4).text).join(',\\ '))}. Choose every set that must be added so that ${mF} is the smallest sigma-algebra containing these.`,
      answer: { kind: 'choice', options, correct: need.map((m) => `s${m}`) },
      solution: [
        t`Add complements: each event's complement must be an event. Then add unions of everything present, and repeat until nothing new appears.`,
        t`The result has ${all.length} events. The ones to add are ${computedTex(need.map((m) => setTex(m, N4).text).join(',\\ '))}.`,
      ],
    };
  },
  solve: ({ gens }) => {
    // The sigma-algebra generated by the events is every union of their atoms.
    const given = new Set([0, ...gens, full(N4)]);
    const groups = new Map<string, number>();
    for (const i of upTo(N4)) {
      const key = gens.map((g) => (g >> (i - 1)) & 1).join('');
      groups.set(key, (groups.get(key) ?? 0) | (1 << (i - 1)));
    }
    const blocks = [...groups.values()];
    const unions = new Set<number>();
    for (let s = 0; s < 1 << blocks.length; s++) unions.add(blocks.reduce((u, b, j) => (((s >> j) & 1) === 1 ? u | b : u), 0));
    return [...unions].filter((m) => !given.has(m)).map((m) => `s${m}`);
  },
  misconceptions: ({ gens }): Misconception[] => {
    const given = new Set([0, ...gens, full(N4)]);
    const comps = gens.map((g) => g ^ full(N4)).filter((m) => !given.has(m));
    const everything = upTo(full(N4) - 1).filter((m) => !given.has(m));
    return [
      { response: [...new Set(comps)].map((m) => `s${m}`), why: t`Complements are needed, but so are unions, and then the complements of those.` },
      { response: everything.map((m) => `s${m}`), why: t`Not every subset is forced: only unions of the pieces the given events cut ${mO} into.` },
    ];
  },
});

