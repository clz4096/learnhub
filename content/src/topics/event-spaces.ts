const q4a = workedProof({
  title: t`Events built from the definition`,
  prompt: t`Let ${mF} be a sigma-algebra on ${mO} and ${math`(A_n : n \in \mathbb{N})`} a sequence of events. Show, starting from the definition, that ${math`\varnothing`}, ${math`A_{${1}} \cup A_{${2}}`}, and ${math`\bigcap_{n = ${1}}^{\infty} A_n`} are events.`,
  steps: [
    t`${math`\varnothing`}: ${math`\Omega \in \mathcal{F}`}, and ${mF} is closed under complements, so ${math`\varnothing = \Omega^{c} \in \mathcal{F}`}.`,
    t`${math`A_{${1}} \cup A_{${2}}`}: the definition only gives countable unions, so pad the pair into a sequence, ${math`A_{${1}}, A_{${2}}, \varnothing, \varnothing, \ldots`}. Every term is an event (${math`\varnothing`} by the first part), so the union of the sequence is an event, and it equals ${math`A_{${1}} \cup A_{${2}}`}.`,
    t`${math`\bigcap_{n} A_n`}: by De Morgan's law, ${math`\bigcap_{n} A_n = \left(\bigcup_{n} A_n^{c}\right)^{c}`}. Each ${math`A_n^{c}`} is an event (complements), so their countable union is (unions), and so is its complement (complements again).`,
  ],
  answer: t`All three are events, using only ${math`\Omega \in \mathcal{F}`}, closure under complements, and closure under countable unions.`,
  source: cite(S1, 'Q4(a)'),
});

